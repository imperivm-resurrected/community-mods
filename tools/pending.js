// Write PENDING.md: the MODS.md rows still to port (📋; MISSING.md has no download, only counted), grouped by what holds them back, with
// where their files are. Regenerate after editing MODS.md:  node tools/pending.js
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const discord = require("../raw/discord-entries.json");
const byLink = Object.fromEntries(discord.map(e => [e.discord, e]));
const slug = s => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// where the downloaded files of a row are, if any
const localOf = (name, source, download = "") => {
  const listed = (download.match(/originals\/[^`)\s]+/) || [])[0]?.replace(/\/$/, "");
  const topic = (source.match(/foroactivo\.com\/t(\d+)-/) || [])[1];
  const e = byLink[(source.match(/\((https:\/\/discord\.com\/channels\/[^)]+)\)/) || [])[1]];
  const dirs = [e && e.files.length && `originals/discord/${e.channel}/${e.slug}`, topic && `originals/forum/t${topic}/files`,
    `originals/forum/${slug(name)}/files`, listed && `${listed}/files`, listed].filter(Boolean);
  const hit = dirs.find(d => fs.existsSync(path.join(ROOT, d)));
  if (!hit) return "—";
  const n = fs.readdirSync(path.join(ROOT, hit), { recursive: true }).filter(f => fs.statSync(path.join(ROOT, hit, f)).isFile()).length;
  return `\`${hit}/\` (${n})`;
};

// [title, test on the Type cell, what to do]
const GROUPS = [
  ["Big mods to reduce or rewrite", t => /^(reduce|rewrite)/.test(t), "`shrink-mod.js` against the HD game, clean up, test. 1.40 mods may undo HD fixes."],
  ["Blocked: needs a mod not ported yet", t => /\(not ported yet\)/.test(t), "Port that mod first, then `node tools/wrap-map.js <entry>`."],
  ["Blocked: needs a mod nobody has", t => /requires \? mod/.test(t), "Find the mod that has those classes, or drop the row."],
  ["Needs a mod, link without its key", t => /^requires/.test(t), "Ask the author for a full link."],
  ["To check: probably maps (wrap?)", t => /^wrap\?/.test(t), "Open the download: only `.bfhp` → wrap; DATA or `.pak` → reduce; nothing → drop."],
  ["Ready to wrap", t => /^wrap/.test(t), "`node tools/wrap-map.js <entry>`."],
  ["To review: maybe not a mod", t => /^review/.test(t), "Tutorial or tool → 🚫; units, items or fixes → reduce (most are in the MCI already)."],
  ["Other", () => true, "Decide by hand."],
];

const rows = [];
let missing = 0;
for (const file of ["MODS.md", "MISSING.md"]) {
  let H;
  for (const l of fs.readFileSync(path.join(ROOT, file), "utf8").split("\n")) {
    if (l.startsWith("| # |")) H = l.split("|").map(s => s.trim());
    const c = l.split("|").map(s => s.trim());
    if (!H || !/^\d+$/.test(c[1] || "") || !/📋/.test(c[H.indexOf("Status")])) continue;
    if (file === "MISSING.md") { missing++; continue; }
    const get = k => c[H.indexOf(k)];
    rows.push({ file, n: c[1], name: get("Name"), author: get("Author(s)"), base: get("Base"), type: get("Type"), source: get("Source"),
      dl: get("Download").split("<br>").filter(p => /^[✅⚠️]/u.test(p)).length, local: localOf(get("Name"), get("Source"), get("Download")) });
  }
}
const left = [...rows];
let md = `# Pending

Generated by \`node tools/pending.js\` from \`MODS.md\` (rows still 📋 to port): ${rows.length} rows, plus ${missing} in \`MISSING.md\` with no download. Do not edit it: change \`MODS.md\` and regenerate it.
Columns: **Local** = downloaded files (count); **Links** = working links in the table.
`;
for (const [title, test, todo] of GROUPS) {
  const xs = left.filter(r => test(r.type));
  if (!xs.length) continue;
  for (const r of xs) left.splice(left.indexOf(r), 1);
  md += `\n## ${title} (${xs.length})\n\n${todo}\n\n| ✓ | # | Name | Author | Base | Type | Local | Links | Notes |\n|---|---|---|---|---|---|---|---|---|\n`;
  md += xs.map(r => `| [ ] | ${r.n} | ${r.name} | ${r.author} | ${r.base} | ${r.type} | ${r.local} | ${r.dl || "—"} | |`).join("\n") + "\n";
}
fs.writeFileSync(path.join(ROOT, "PENDING.md"), md);
console.log(`PENDING.md: ${rows.length} rows`);
