// Tables of what the ported civilization mods have and how they differ (GREEK-MODS.md):
//   node tools/compare-mods.js > GREEK-MODS.md
// Every figure comes from the ported mods (ported/<id>/DATA/CLASSES, civs/) and from the game's own classes: nothing is typed by hand.
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const HDC = path.join(ROOT, "originals", "game-data", "paks", "DATA", "CLASSES");
const MODS = [
  { id: "cgwar", label: "CGWAR", author: "Camarada, Gurkhan, Razor, WARRIOR4444", ver: "6", base: "1.40", greek: /^K[A-Z]/, race: "greece" },
  { id: "greek-mod-1-8", label: "Rattlesmake 1.8", author: "Rattlesmake", ver: "1.8", base: "1.40", greek: /^Q[A-Z]/, race: "greek18" },
  { id: "greek-civilization-mod", label: "Gabbo 4.2", author: "Gabbo", ver: "4.2", base: "HD", greek: /^H[A-Z]/, race: "greek" },
];
const rd = f => fs.readFileSync(f, "latin1");
const readJson = f => { try { return JSON.parse(fs.readFileSync(f, "utf8")); } catch (e) { console.error(`${f}: ${e.message}`); process.exit(1); } };
const walk = (d, out = []) => { if (!fs.existsSync(d)) return out; for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p, out); else out.push(p); } return out; };
const classes = dir => { const m = new Map(); for (const f of fs.readdirSync(dir, { withFileTypes: true }).filter(e => e.isFile() && /\.sc\.xml$/i.test(e.name))) { const t = rd(path.join(dir, f.name)), id = (t.match(/<class\b[^>]*?\bid\s*=\s*"([^"]+)"/) || [])[1]; if (id) m.set(id.toLowerCase(), { id, text: t }); } return m; };
const hd = classes(HDC);
const attr = (t, a) => { let v; for (const m of t.matchAll(new RegExp(`<properties\\b[^>]*?\\b${a}\\s*=\\s*"([^"]*)"`, "gi"))) v = m[1]; return v; };       // the last one wins
const own = (t, a) => attr(t.replace(/<!--[\s\S]*?-->/g, ""), a);
const effective = (tbl, id, a) => { for (let c = tbl.get(id.toLowerCase()), n = 0; c && n < 20; n++) { const v = own(c.text, a); if (v !== undefined) return v; const p = (c.text.match(/<class\b[^>]*?\bparent\s*=\s*"([^"]+)"/) || [])[1]; c = p && (tbl.get(p.toLowerCase()) || hd.get(p.toLowerCase())); } return undefined; };
const display = t => (t.match(/display_name\s*=\s*"([^"]*)"/) || [])[1] || "";
const STATS = ["maxhealth", "damage", "armor_slash", "speed", "range"];
const row = (tbl, id) => STATS.map(a => effective(tbl, id, a) ?? "·").join(" / ");

const out = [];
const w = s => out.push(s);
w("# The Greek mods side by side\n");
w("Generated by `node tools/compare-mods.js` from `ported/`. Stats are `health / damage / slash armor / speed / range` as the classes say (the game's own value when the class does not set it).\n");

// 1. the mods
w("## The mods\n");
w("| | CGWAR | Rattlesmake 1.8 | Gabbo 4.2 |");
w("|---|---|---|---|");
const civsOf = m => walk(path.join(ROOT, "ported", m.id, "civs")).filter(f => /\.json$/i.test(f)).map(readJson);
const info = MODS.map(m => {
  const civs = civsOf(m), mj = readJson(path.join(ROOT, "ported", m.id, "mod.json"));
  const tbl = classes(path.join(ROOT, "ported", m.id, "DATA", "CLASSES"));
  const greekCls = [...tbl.values()].filter(c => new RegExp(`race\\s*=\\s*"${m.race}"`, "i").test(c.text));
  const files = walk(path.join(ROOT, "ported", m.id)), cnt = re => files.filter(f => re.test(path.relative(path.join(ROOT, "ported", m.id), f).replace(/\\/g, "/"))).length;
  return { m, civs, mj, tbl, greekCls, maps: cnt(/^(scenarios|adventures|conquests|conquestmaps)\/.*\.bfhp$/i), music: cnt(/^music\//i), size: files.reduce((a, f) => a + fs.statSync(f).size, 0) };
});
const line = (name, f) => w(`| ${name} | ${info.map(f).join(" | ")} |`);
line("Author", i => i.m.author);
line("Made for", i => i.m.base === "HD" ? "Imperivm HD" : "Imperivm III 1.40 (ported to HD)");
line("Civilizations in the lobby", i => `${i.civs.length}`);
line("Letters (index)", i => [...i.civs].sort((a, b) => a.index - b.index).map(c => `${c.letter || "·"} (${c.index})`).join(", "));
line("Greece", i => `\`${i.m.race}\`, ${i.greekCls.length} classes`);
line("Game civilizations changed as their own copies", i => `${i.civs.length - 1}`);
line("Maps, adventures, conquests", i => `${i.maps}`);
line("Music tracks", i => `${i.music}`);
line("Size", i => `${(i.size / 1e9).toFixed(2)} GB`);
w("");
w("| Civilization (lobby) | Id | Letter | Index |");
w("|---|---|---|---|");
for (const i of info) for (const c of i.civs.sort((a, b) => a.index - b.index)) w(`| ${c.name.english} | \`${c.id}\` | ${c.letter || "·"} | ${c.index} |`);
w("");

// 2. the Greek rosters
w("## Greece: the three rosters\n");
const rosters = info.map(i => [...i.tbl.values()].filter(c => i.m.greek.test(c.id) && new RegExp(`race\\s*=\\s*"${i.m.race}"|parent\\s*=\\s*"(?!Hero)`, "i").test(c.text) && /cpp_class\s*=\s*"CVX(Unit|Hero)"/.test(c.text) && !/Hero\d|Sentry|Villager|Ambient|House|Wall|Gate|Tower/i.test(c.id)));
for (let k = 0; k < info.length; k++) {
  w(`### ${info[k].m.label}\n`);
  w("| Class | Name | Health / damage / armor / speed / range |");
  w("|---|---|---|");
  for (const c of rosters[k].sort((a, b) => a.id.localeCompare(b.id))) w(`| \`${c.id}\` | ${display(c.text) || "·"} | ${row(info[k].tbl, c.id)} |`);
  w("");
}

// 3. what each changed in the game's civilizations
w("## What each mod changed in the game's civilizations\n");
w("Only units whose own stats differ from HD. The CGWAR changes none: its classes are Greece's. La Reconquista 2010 is not a Greek mod: it is here because it changes the same classes.\n");
const GAME = { G: "Gaul", M: "Imperial Rome", R: "Republican Rome", C: "Carthage", I: "Iberia", B: "Britain", E: "Egypt", T: "Germany" };
w("| Civilization | Unit | HD | Rattlesmake 1.8 | Gabbo 4.2 | La Reconquista 2010 |");
w("|---|---|---|---|---|---|");
const merged = id => classes(path.join(ROOT, "originals", id, "classes"));
const mod18 = merged("greek-1-8-merged"), mod42 = merged("greek-4-2-merged"), mod10 = merged("la-reconquista-2010-merged");   // La Reconquista changes the game's eight and adds no Greece
const ids = new Set();
for (const t of [mod18, mod42, mod10]) for (const [k, c] of t) if (hd.has(k) && GAME[c.id[0]] && /^[A-Z][A-Z]/.test(c.id) && /cpp_class\s*=\s*"CVX(Unit|Hero)"/.test(c.text) && !/Sentry/.test(c.id)) ids.add(c.id);
for (const id of [...ids].sort()) {
  const h = row(hd, id), a = mod18.has(id.toLowerCase()) ? row(mod18, id) : h, b = mod42.has(id.toLowerCase()) ? row(mod42, id) : h, c = mod10.has(id.toLowerCase()) ? row(mod10, id) : h;
  if (a === h && b === h && c === h) continue;
  w(`| ${GAME[id[0]]} | \`${id}\` ${display(hd.get(id.toLowerCase()).text)} | ${h} | ${a === h ? "=" : a} | ${b === h ? "=" : b} | ${c === h ? "=" : c} |`);
}
w("");
// 4. Greece's researches and orders: what each mod gives it
w("## Greece: researches and orders\n");
w("The researches in each mod's own Greek command file (`method=\"research\"`); a mark means it has one with that name (up to the tag a port adds to avoid clashes). Researches the mod adds to a shared command file are not counted.\n");
const GREEK_FILES = { "cgwar": /GREECE/i, "greek-mod-1-8": /GREEK18/i, "greek-civilization-mod": /GREEK42/i };
const strip = n => n.replace(/\s*\((g42|g18|cgwar)\)$/i, "").trim();
const researches = info.map(i => { const dir = path.join(ROOT, "ported", i.m.id, "DATA", "COMMANDS"), set = new Map(); for (const f of fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => GREEK_FILES[i.m.id].test(f)) : []) for (const m of rd(path.join(dir, f)).replace(/<!--[\s\S]*?-->/g, "").matchAll(/<cmd\b([^>]*)>[\s\S]*?<\/cmd>/g)) { if (!/method\s*=\s*"research"/.test(m[1] + m[0])) continue; const n = (m[1].match(/\bname\s*=\s*"([^"]*)"/) || [])[1]; if (n) set.set(strip(n).toLowerCase(), strip(n)); } return set; });
const all = new Map(); for (const r of researches) for (const [k, v] of r) all.set(k, v);
w(`| Research | ${info.map(i => i.m.label).join(" | ")} |`);
w("|---|---|---|---|");
for (const [k, v] of [...all].sort((a, b) => a[0].localeCompare(b[0]))) w(`| ${v} | ${researches.map(r => r.has(k) ? "✔" : "").join(" | ")} |`);
w(`| **Total** | ${researches.map(r => r.size).join(" | ")} |`);
w("");
console.log(out.join("\n"));
